#!/usr/bin/env zsh

# Run docker compose with whichever CLI flavour is available.
_DockerCompose() {
  if docker compose version >/dev/null 2>&1; then
    docker compose "$@"
  elif command -v docker-compose >/dev/null 2>&1; then
    docker-compose "$@"
  else
    EchoFatal "docker compose not found; please install Docker Desktop or docker-compose"
    return 1
  fi
}

_CheckDockerCompose() {
  if docker compose version >/dev/null 2>&1; then
    return 0
  elif command -v docker-compose >/dev/null 2>&1; then
    return 0
  fi
  return 1
}

_CheckDockerAvailable() {
  command -v docker >/dev/null 2>&1 || return 1
  docker info >/dev/null 2>&1 || return 1
  _CheckDockerCompose
}

_CheckNativeR() {
  command -v Rscript >/dev/null 2>&1
}

_NowSeconds() {
  date +%s
}

_AcquireDirLock() {
  local lock_dir="$1"
  local timeout="${2:-900}"
  local start=$(_NowSeconds)
  local now="$start"
  local pid_file="$lock_dir/pid"
  local lock_pid="" lock_host="" current_host=""

  current_host="$(hostname 2>/dev/null || echo unknown)"
  while ! mkdir "$lock_dir" 2>/dev/null; do
    lock_pid=""
    lock_host=""
    if [[ -f "$pid_file" ]]; then
      read -r lock_pid lock_host < "$pid_file" || true
      if [[ -n "$lock_pid" && "$lock_host" == "$current_host" ]] && ! kill -0 "$lock_pid" 2>/dev/null; then
        EchoWarn "Removing stale plot lock: $lock_dir"
        rm -rf "$lock_dir"
        continue
      fi
    fi

    now=$(_NowSeconds)
    if (( now - start >= timeout )); then
      EchoFatal "timed out waiting for plot lock: $lock_dir"
      return 1
    fi
    EchoStep "Waiting for plot lock: $lock_dir"
    sleep 2
  done

  printf '%s %s\n' "$$" "$current_host" > "$pid_file"
}

_ReleaseDirLock() {
  local lock_dir="$1"
  rm -rf "$lock_dir"
}

_DockerImageExists() {
  local image="$1"
  docker image inspect "$image" >/dev/null 2>&1
}

_PlotsDockerfileHash() {
  local plots_dir="$1"
  local dockerfile="$plots_dir/Dockerfile"

  if [[ ! -f "$dockerfile" ]]; then
    EchoFatal "plots Dockerfile not found at $dockerfile"
    return 1
  fi

  HashString "$(<"$dockerfile")"
}

_PlotsDockerImage() {
  local plots_dir="$1"
  local hash=""

  hash=$(_PlotsDockerfileHash "$plots_dir") || return 1
  echo "mkexp2-plots:${hash[1,12]}"
}

_PreparePlotsBuildContext() {
  local plots_dir="$1"
  local build_context="$2"

  mkdir -p "$build_context"
  cp "$plots_dir/Dockerfile" "$build_context/Dockerfile"
  printf '%s\n' '*' '!Dockerfile' > "$build_context/.dockerignore"
}

# Write a docker-compose file tailored for a single plotting run.
# $1 = plots submodule dir (absolute)
# $2 = results dir          (absolute, mounted read-only as /data)
# $3 = experiment dir       (absolute, mounted read-write as /output)
# $4 = Docker image tag
# $5 = Docker build context  (absolute, generated by mkexp2)
# $6 = destination file
_WritePlotsComposeFile() {
  local plots_dir="$1"
  local results_dir="$2"
  local experiment_dir="$3"
  local image="$4"
  local build_context="$5"
  local dest="$6"

  # Use printf so we control every byte; no heredoc quoting surprises.
  printf '%s\n' \
    '# Generated by mkexp2 plot -- do not edit manually' \
    'services:' \
    '  plot:' \
    "    image: ${image}" \
    '    build:' \
    "      context: ${build_context}" \
    '      dockerfile: Dockerfile' \
    '    working_dir: /work' \
    '    volumes:' \
    "      - ${plots_dir}:/work:ro" \
    "      - ${results_dir}:/data:ro" \
    "      - ${experiment_dir}:/output" \
    "      - ${plots_dir}/.r-libs:/usr/local/lib/R/site-library" \
    "      - ${plots_dir}/.cache:/cache" \
    '    environment:' \
    '      - TZ=Europe/Berlin' \
    '    init: true' \
    > "$dest"
}

typeset -a PLOT_R_ARGS=()
typeset -a PLOT_SOURCE_ARGS_NATIVE=()
typeset -a PLOT_SOURCE_ARGS_DOCKER=()
typeset -gi _PLOT_SPACK_PACKAGES_LOADED=0

PrintPlotCatalog() {
  local json="${1:-0}"
  local plots_dir="$MKEXP2_HOME/plots"
  local mkexp_script="$plots_dir/mkexp.R"
  local -a args=(plot --list)

  if [[ ! -f "$mkexp_script" ]]; then
    EchoFatal "plots catalog entrypoint not found: $mkexp_script"
    return 1
  fi
  if ! command -v Rscript >/dev/null 2>&1; then
    EchoFatal "Rscript not found; mkexp2 plot --list requires the plots R entrypoint"
    return 1
  fi
  if (( json )); then
    args+=(--json)
  fi

  (
    unset R_HOME
    Rscript "$mkexp_script" "${args[@]}"
  )
}

_BuildPlotRArgs() {
  local do_pp="$1"
  local do_speedup="$2"
  local do_rt="$3"
  local output_file="/output/plots.pdf"
  if (( $# >= 4 )); then
    output_file="$4"
    shift 4
  else
    shift 3
  fi

  PLOT_R_ARGS=()
  (( do_pp ))      && PLOT_R_ARGS+=("--performance-profile")
  (( do_speedup )) && PLOT_R_ARGS+=("--speedup")
  (( do_rt ))      && PLOT_R_ARGS+=("--running-time")
  if [[ -n "$MKEXP2_PLOT_THREADS" ]]; then
    PLOT_R_ARGS+=("--threads" "$MKEXP2_PLOT_THREADS")
  fi
  PLOT_R_ARGS+=("--output" "$output_file")
  PLOT_R_ARGS+=("$@")
}

_BuildManagedPlotRArgs() {
  local output_file="$1"
  shift

  PLOT_R_ARGS=()
  local plot_id=""
  for plot_id in "${MKEXP2_PLOT_TYPES[@]}"; do
    PLOT_R_ARGS+=("--plot" "$plot_id")
  done
  if [[ -n "$MKEXP2_PLOT_THREADS" ]]; then
    PLOT_R_ARGS+=("--threads" "$MKEXP2_PLOT_THREADS")
  fi
  PLOT_R_ARGS+=("--output" "$output_file")
  PLOT_R_ARGS+=("$@")
}

_PlotSourcePathPart() {
  local source="$1"
  if [[ "$source" == *=* ]]; then
    printf '%s' "${source#*=}"
  else
    printf '%s' "$source"
  fi
}

_PlotSourceAliasPart() {
  local source="$1"
  local source_path=""
  if [[ "$source" == *=* ]]; then
    printf '%s' "${source%%=*}"
    return
  fi
  source_path="$(_PlotSourcePathPart "$source")"
  if _PlotSourceLooksLikeCsvPath "$source_path"; then
    printf '%s' "${source_path:t:r}"
  else
    printf '%s' "$source"
  fi
}

_PlotSourceLooksLikeCsvPath() {
  local source="$1"
  [[ "$source" == *.csv || "$source" == */* || "$source" == ./* || "$source" == ../* ]]
}

_SlugForFileName() {
  local value="$1"
  value="${value:l}"
  value="${value//[^a-z0-9._-]/-}"
  value="${value##-}"
  value="${value%%-}"
  [[ -n "$value" ]] || value="source"
  printf '%s' "$value"
}

_PreparePlotSources() {
  local experiment_dir="$1"
  local -a sources=("${@:2}")
  local stage_dir="$experiment_dir/.mkexp2/plot-inputs/$MKEXP2_RUN_ID"
  local source="" source_path="" alias="" abs_path="" hash="" slug="" staged=""

  PLOT_SOURCE_ARGS_NATIVE=()
  PLOT_SOURCE_ARGS_DOCKER=()

  for source in "${sources[@]}"; do
    source_path="$(_PlotSourcePathPart "$source")"
    alias="$(_PlotSourceAliasPart "$source")"
    if _PlotSourceLooksLikeCsvPath "$source_path"; then
      if [[ "$source_path" == /* ]]; then
        abs_path="$source_path"
      else
        abs_path="$PWD/$source_path"
      fi
      abs_path="${abs_path:A}"
      if [[ ! -f "$abs_path" ]]; then
        EchoFatal "CSV source not found: $source_path"
        return 1
      fi
      mkdir -p "$stage_dir"
      hash="$(HashString "$abs_path")"
      slug="$(_SlugForFileName "$alias")"
      staged="$stage_dir/${slug}-${hash[1,10]}.csv"
      cp "$abs_path" "$staged"
      PLOT_SOURCE_ARGS_NATIVE+=("$alias=$staged")
      PLOT_SOURCE_ARGS_DOCKER+=("$alias=/output/.mkexp2/plot-inputs/$MKEXP2_RUN_ID/${staged:t}")
    else
      PLOT_SOURCE_ARGS_NATIVE+=("$source")
      PLOT_SOURCE_ARGS_DOCKER+=("$source")
    fi
  done
}

_OutputPathForNative() {
  local experiment_dir="$1"
  local output_file="${MKEXP2_PLOT_OUTPUT:-$experiment_dir/plots.pdf}"
  if [[ "$output_file" == /* ]]; then
    printf '%s' "$output_file"
  else
    printf '%s' "$experiment_dir/$output_file"
  fi
}

_OutputPathForDocker() {
  local experiment_dir="$1"
  local output_file="$2"
  local abs_output=""
  local rel_output=""

  if [[ "$output_file" == /* ]]; then
    abs_output="${output_file:A}"
  else
    abs_output="${experiment_dir:A}/$output_file"
  fi
  abs_output="${abs_output:A}"
  if [[ "$abs_output" == "${experiment_dir:A}" ]]; then
    printf '/output'
    return 0
  fi
  if [[ "$abs_output" != "${experiment_dir:A}/"* ]]; then
    EchoFatal "Docker plot output must be inside the experiment directory: $output_file"
    return 1
  fi
  rel_output="${abs_output#${experiment_dir:A}/}"
  printf '/output/%s' "$rel_output"
}

_MaybeLoadSpackRPackage() {
  local package="$1"

  command -v spack >/dev/null 2>&1 || return 1

  local spack_env=""
  spack_env="$(spack load --sh "$package" 2>/dev/null)" || return 1
  [[ -n "$spack_env" ]] || return 1

  eval "$spack_env"
}

_MaybeLoadSpackPlotPackages() {
  local native_cache="${1:-}"
  local cache_file=""
  local cached_r_libs=""
  local package=""
  local spack_env=""
  local before_r_libs="${R_LIBS:-}"

  (( _PLOT_SPACK_PACKAGES_LOADED )) && return 0
  _PLOT_SPACK_PACKAGES_LOADED=1

  if [[ -n "$native_cache" ]]; then
    mkdir -p "$native_cache"
    cache_file="$native_cache/spack-r-libs.txt"
    if [[ -s "$cache_file" ]]; then
      cached_r_libs="$(<"$cache_file")"
      if [[ -n "$cached_r_libs" ]]; then
        export R_LIBS="$cached_r_libs${R_LIBS:+:$R_LIBS}"
        return 0
      fi
    fi
  fi

  command -v spack >/dev/null 2>&1 || return 1

  if spack_env="$(spack load --sh r-tidyverse r-cli r-rcolorbrewer 2>/dev/null)" && [[ -n "$spack_env" ]]; then
    eval "$spack_env"
  else
    for package in r-tidyverse r-plyr r-cli r-rcolorbrewer; do
      _MaybeLoadSpackRPackage "$package" >/dev/null 2>&1 || true
    done
  fi

  if [[ -n "$cache_file" && -n "${R_LIBS:-}" && "${R_LIBS:-}" != "$before_r_libs" ]]; then
    print -r -- "$R_LIBS" > "$cache_file.tmp"
    mv -f "$cache_file.tmp" "$cache_file"
  fi
}

ResolveSpackPlotRLibs() {
  local force="${1:-0}"
  local native_cache="$MKEXP2_HOME/plots/.cache-native"
  local cache_file="$native_cache/spack-r-libs.txt"
  local cached_r_libs=""
  local -a cached_entries=()

  mkdir -p "$native_cache"
  if (( force )); then
    rm -f "$cache_file"
  fi

  _PLOT_SPACK_PACKAGES_LOADED=0
  _MaybeLoadSpackPlotPackages "$native_cache" || true

  if [[ -s "$cache_file" ]]; then
    cached_r_libs="$(<"$cache_file")"
    cached_entries=("${(@s.:.)cached_r_libs}")
    EchoStep "Spack R library cache: $cache_file"
    EchoStep "Spack R library entries: ${#cached_entries}"
    return 0
  fi

  EchoWarn "No Spack R library cache was written; native plotting will use the regular R library paths"
  return 0
}

_RunNativeRscript() {
  local plots_dir="$1"
  local results_dir="$2"
  local script="$3"
  shift 3

  local native_lib="$plots_dir/.r-libs-native"
  local native_cache="$plots_dir/.cache-native"
  local native_user_libs=""
  local native_libs=""
  mkdir -p "$native_lib" "$native_cache"
  _MaybeLoadSpackPlotPackages "$native_cache" || true

  (
    cd "$plots_dir" || exit 1
    native_user_libs="$native_lib"
    if [[ -n "${R_LIBS_USER:-}" ]]; then
      native_user_libs="$native_user_libs:$R_LIBS_USER"
    fi
    native_libs="$native_lib"
    if [[ -n "${R_LIBS:-}" ]]; then
      native_libs="$native_libs:$R_LIBS"
    fi
    env \
      R_LIBS="$native_libs" \
      R_LIBS_USER="$native_user_libs" \
      MKEXP2_PLOTS_NATIVE=1 \
      MKEXP2_PLOTS_DATA_DIR="$results_dir" \
      MKEXP2_PLOTS_CACHE_DIR="$native_cache" \
      MKEXP2_PLOTS_DATA_OUTPUT_DIR="$results_dir" \
      Rscript "$script" "$@"
  )
}

_InstallNativeRPackages() {
  local plots_dir="$1"
  local results_dir="$2"
  local lock_dir="$plots_dir/.r-libs-native.lock"
  local rc=0

  EchoStep "Checking native R packages"
  _AcquireDirLock "$lock_dir" 900 || return 1
  {
    _RunNativeRscript "$plots_dir" "$results_dir" "$plots_dir/install.R"
    rc=$?
  } always {
    _ReleaseDirLock "$lock_dir"
  }
  if (( rc != 0 )); then
    EchoFatal "native R package installation failed"
    return 1
  fi
}

_GeneratePlotsWithDocker() {
  local plots_dir="$1"
  local results_dir="$2"
  local experiment_dir="$3"
  shift 3

  mkdir -p "$experiment_dir/.mkexp2"
  local compose_file="$experiment_dir/.mkexp2/plots-compose.yml"
  local build_context="$experiment_dir/.mkexp2/plots-image"
  local image=""

  image=$(_PlotsDockerImage "$plots_dir") || return 1
  _PreparePlotsBuildContext "$plots_dir" "$build_context"
  _WritePlotsComposeFile "$plots_dir" "$results_dir" "$experiment_dir" "$image" "$build_context" "$compose_file"

  if _DockerImageExists "$image"; then
    EchoStep "Using cached plots Docker image: $image"
  else
    EchoStep "Building plots Docker image: $image (first run for this Dockerfile)"
    if ! _DockerCompose -f "$compose_file" build plot; then
      EchoFatal "failed to build plots Docker image"
      return 1
    fi
  fi

  mkdir -p "$plots_dir/.r-libs"
  if [[ -z "$(ls -A "$plots_dir/.r-libs" 2>/dev/null)" ]]; then
    EchoStep "Installing R packages into $plots_dir/.r-libs (first run, this takes a while)"
    if ! _DockerCompose -f "$compose_file" run --rm plot \
        Rscript /work/install.R; then
      EchoFatal "R package installation failed"
      return 1
    fi
  fi

  local output_file=""
  output_file="$(_OutputPathForDocker "$experiment_dir" "${MKEXP2_PLOT_OUTPUT:-plots.pdf}")" || return 1
  if (( ${#MKEXP2_PLOT_TYPES[@]} > 0 )); then
    _BuildManagedPlotRArgs "$output_file" "${PLOT_SOURCE_ARGS_DOCKER[@]}"
  else
    _BuildPlotRArgs "$1" "$2" "$3" "$output_file" "${PLOT_SOURCE_ARGS_DOCKER[@]}"
  fi

  EchoStep "Generating plots with Docker"
  if ! _DockerCompose -f "$compose_file" run --rm plot \
      Rscript /work/mkexp.R plot "${PLOT_R_ARGS[@]}"; then
    EchoFatal "plot generation failed"
    return 1
  fi
}

_GeneratePlotsWithNativeR() {
  local plots_dir="$1"
  local results_dir="$2"
  local experiment_dir="$3"
  shift 3

  if ! _CheckNativeR; then
    EchoFatal "Docker is unavailable and Rscript was not found"
    return 1
  fi

  _InstallNativeRPackages "$plots_dir" "$results_dir" || return 1
  local output_file=""
  output_file="$(_OutputPathForNative "$experiment_dir")"
  if (( ${#MKEXP2_PLOT_TYPES[@]} > 0 )); then
    _BuildManagedPlotRArgs "$output_file" "${PLOT_SOURCE_ARGS_NATIVE[@]}"
  else
    _BuildPlotRArgs "$1" "$2" "$3" "$output_file" "${PLOT_SOURCE_ARGS_NATIVE[@]}"
  fi

  EchoStep "Generating plots with native R"
  if ! _RunNativeRscript "$plots_dir" "$results_dir" "$plots_dir/mkexp.R" plot "${PLOT_R_ARGS[@]}"; then
    EchoFatal "native plot generation failed"
    return 1
  fi
}

GeneratePlots() {
  local plots_dir="$MKEXP2_HOME/plots"
  local results_dir="$PWD/results"
  local experiment_dir="$PWD"
  local output_file=""

  # ── Validate prerequisites ──────────────────────────────────────────────────

  if [[ ! -f "$plots_dir/mkexp.R" || ! -f "$plots_dir/R/common.R" ]]; then
    EchoFatal "plots submodule not initialized at $plots_dir"
    EchoFatal "Run: git submodule update --init plots"
    return 1
  fi

  # ── Determine active algorithms ─────────────────────────────────────────────

  local -a active_algos=()

  if (( ${#MKEXP2_PLOT_ALGORITHMS[@]} > 0 )); then
    active_algos=("${MKEXP2_PLOT_ALGORITHMS[@]}")
  else
    # Collect algorithms from every Experiment* function, deduplicated.
    local -a exp_fns=()
    exp_fns=($(DiscoverExperimentFunctions "$PWD/Experiment"))

    if (( ${#exp_fns[@]} == 0 )); then
      EchoFatal "no Experiment*() functions found in Experiment"
      return 1
    fi

    local fn="" algo=""
    for fn in "${exp_fns[@]}"; do
      LoadExperimentFunctionState "$PWD/Experiment" "$fn"
      for algo in "${_algorithms[@]}"; do
        if (( ${active_algos[(Ie)$algo]} == 0 )); then
          active_algos+=("$algo")
        fi
      done
    done
  fi

  if (( ${#active_algos[@]} == 0 )); then
    EchoWarn "no algorithms found; nothing to plot"
    return 0
  fi

  output_file="$(_OutputPathForNative "$experiment_dir")"

  EchoStep "Active algorithms: ${(j:, :)active_algos}"
  if [[ -n "$MKEXP2_PLOT_THREADS" ]]; then
    EchoStep "Plot thread filter: $MKEXP2_PLOT_THREADS"
  fi

  # ── Warn about missing CSV files ────────────────────────────────────────────

  local algo=""
  for algo in "${active_algos[@]}"; do
    if _PlotSourceLooksLikeCsvPath "$(_PlotSourcePathPart "$algo")"; then
      continue
    fi
    if [[ ! -f "$results_dir/${algo}.csv" ]]; then
      EchoWarn "CSV not found: $results_dir/${algo}.csv (run mkexp2 parse first)"
    fi
  done

  # ── Determine which plots to generate ──────────────────────────────────────

  local do_pp=$MKEXP2_PLOT_PERFORMANCE_PROFILE
  local do_speedup=$MKEXP2_PLOT_SPEEDUP
  local do_rt=$MKEXP2_PLOT_RUNNING_TIME

  if (( !MKEXP2_PLOT_EXPLICIT_SELECTION )); then
    do_pp=1
    do_speedup=1
    do_rt=1
  fi

  _PreparePlotSources "$experiment_dir" "${active_algos[@]}" || return 1

  # ── Generate plots ─────────────────────────────────────────────────────────

  if (( MKEXP2_PLOT_NO_DOCKER )); then
    EchoStep "Docker disabled; using native R"
    _GeneratePlotsWithNativeR "$plots_dir" "$results_dir" "$experiment_dir" \
      "$do_pp" "$do_speedup" "$do_rt" || return 1
  elif _CheckDockerAvailable; then
    _GeneratePlotsWithDocker "$plots_dir" "$results_dir" "$experiment_dir" \
      "$do_pp" "$do_speedup" "$do_rt" || return 1
  else
    EchoWarn "Docker is not available; falling back to native R"
    _GeneratePlotsWithNativeR "$plots_dir" "$results_dir" "$experiment_dir" \
      "$do_pp" "$do_speedup" "$do_rt" || return 1
  fi

  if [[ ! -s "$output_file" ]]; then
    EchoFatal "plot generation finished without creating $output_file"
    return 1
  fi

  # ── Ensure plots.pdf is ignored by git ─────────────────────────────────────

  local gitignore_file="$PWD/.gitignore"
  if [[ -f "$gitignore_file" ]]; then
    if [[ "${output_file:A}" == "${experiment_dir:A}/plots/"* ]]; then
      if ! grep -qxF "plots/" "$gitignore_file"; then
        printf '%s\n' "plots/" >> "$gitignore_file"
      fi
    elif [[ "${output_file:A}" == "${experiment_dir:A}/plots.pdf" ]]; then
      if ! grep -qxF "plots.pdf" "$gitignore_file"; then
        printf '%s\n' "plots.pdf" >> "$gitignore_file"
      fi
    fi
  fi

  EchoStep "Done: $output_file"
}
